/**
 * Builds the synthetic surface-sequence document from the story, and serializes it.
 * `npm run gen:data` (scripts/generate-synthetic.ts) is the only writer of the committed file.
 *
 * Pure: no I/O here. The script does the writing.
 */
import type { Sequence } from '../lib/contract.ts'
import { ssviW } from './ssvi.ts'
import { buildDateParams, STORY, type Story } from './story.ts'

export const MAX_BYTES = 20_000_000

/** Unrounded implied vols sqrt(w / T), indexed [date][dte][k]. */
export function analyticIv(story: Story): number[][][] {
  const params = buildDateParams(story)
  return params.map((p) =>
    story.grid.dte.map((d, i) => story.grid.k.map((k) => Math.sqrt(ssviW(k, { theta: p.theta[i], rho: p.rho, eta: p.eta }) / (d / 365)))),
  )
}

const round6 = (x: number) => Math.round(x * 1e6) / 1e6

export function generate(story: Story = STORY): Sequence {
  const params = buildDateParams(story)
  const iv = analyticIv(story)
  return {
    schema: 'vol-surface-cinema/surface-sequence',
    schema_version: 1,
    id: story.id,
    title: story.title,
    badge: story.badge,
    synthetic: true,
    grid: { k: story.grid.k, dte: story.grid.dte },
    frames: params.map((p, t) => ({ date: p.date, iv: iv[t].map((row) => row.map(round6)) })),
    events: story.events.map((e) => ({ date: params[e.dateIndex].date, label: e.label, kind: e.kind })),
    playback: { ...story.playback },
    source: {
      kind: 'synthetic',
      notice: 'Generated by scripts/generate-synthetic.ts from a seeded SSVI regime story. Not market data. Dates are fictional.',
      generator: { script: 'scripts/generate-synthetic.ts', seed: story.seed },
    },
    licence: 'MIT',
  }
}

/** The exact bytes written to disk. Throws when they would exceed `maxBytes`. */
export function serialize(doc: Sequence, maxBytes: number = MAX_BYTES): string {
  const text = JSON.stringify(doc, null, 2) + '\n'
  const bytes = new TextEncoder().encode(text).length
  if (bytes > maxBytes) throw new RangeError(`refusing to write ${bytes} bytes: over the ${maxBytes} byte limit`)
  return text
}
